// Synthesizes the English narration with the Kokoro-82M text-to-speech model.
//   node narrate.mjs [--voice am_michael] [--speed 1]
// Reads caption texts from out/meta.json, writes out/narration/<scene>_<n>.wav and
// src/narration.js (clip durations, used by the engine to time each caption).
// The model is downloaded from huggingface.co on first use and cached.
import { KokoroTTS } from 'kokoro-js';
import fs from 'fs'; import path from 'path'; import crypto from 'crypto';
const arg = (k, d) => { const i = process.argv.indexOf('--' + k); return i < 0 ? d : process.argv[i + 1]; };
const VOICE = arg('voice', 'am_michael'), SPEED = +arg('speed', 1), SR = 24000, DIR = 'out/narration';
const meta = JSON.parse(fs.readFileSync('out/meta.json', 'utf8'));
fs.mkdirSync(DIR, { recursive: true });
const idxFile = path.join(DIR, 'index.json'), idx = fs.existsSync(idxFile) ? JSON.parse(fs.readFileSync(idxFile, 'utf8')) : {};
const tts = await KokoroTTS.from_pretrained('onnx-community/Kokoro-82M-v1.0-ONNX', { dtype: 'fp32', device: 'cpu' });
const trim = a => { const th = 0.004; let i = 0, j = a.length - 1; while (i < j && Math.abs(a[i]) < th) i++; while (j > i && Math.abs(a[j]) < th) j--; return a.slice(Math.max(0, i - 600), Math.min(a.length, j + 1200)); };
const wav = (file, a) => { const b = Buffer.alloc(44 + a.length * 2); b.write('RIFF', 0); b.writeUInt32LE(36 + a.length * 2, 4); b.write('WAVEfmt ', 8); b.writeUInt32LE(16, 16); b.writeUInt16LE(1, 20); b.writeUInt16LE(1, 22); b.writeUInt32LE(SR, 24); b.writeUInt32LE(SR * 2, 28); b.writeUInt16LE(2, 32); b.writeUInt16LE(16, 34); b.write('data', 36); b.writeUInt32LE(a.length * 2, 40); for (let i = 0; i < a.length; i++) b.writeInt16LE(Math.round(Math.max(-1, Math.min(1, a[i])) * 32767), 44 + i * 2); fs.writeFileSync(file, b); };
const durs = {}; let total = 0;
for (const s of meta.scenes) {
  durs[s.id] = [];
  for (let i = 0; i < s.cues.length; i++) {
    const text = s.cues[i].say || s.cues[i].text, key = `${s.id}_${i}`, file = path.join(DIR, key + '.wav');
    const h = crypto.createHash('sha1').update(`${VOICE}|${SPEED}|${text}`).digest('hex');
    if (!(idx[key]?.h === h && fs.existsSync(file))) {
      // one sentence per call keeps every request well under the model's token limit
      const parts = [];
      for (const sent of text.match(/[^.!?]+[.!?]+|[^.!?]+$/g).map(x => x.trim()).filter(Boolean)) {
        const a = await tts.generate(sent, { voice: VOICE, speed: SPEED });
        parts.push(trim(a.audio), new Float32Array(Math.round(SR * 0.28)));
      }
      parts.pop();
      const all = new Float32Array(parts.reduce((n, p) => n + p.length, 0)); let o = 0; for (const p of parts) { all.set(p, o); o += p.length; }
      wav(file, all); idx[key] = { h, dur: all.length / SR, text };
      console.log(key, idx[key].dur.toFixed(2) + ' s');
    }
    durs[s.id].push(+idx[key].dur.toFixed(3)); total += idx[key].dur;
  }
}
fs.writeFileSync(idxFile, JSON.stringify(idx, null, 1));
fs.writeFileSync('src/narration.js', `// Generated by narrate.mjs: narration clip durations in seconds (voice ${VOICE}).\nwindow.NARR = ${JSON.stringify(durs)};\n`);
console.log(`narration: ${total.toFixed(1)} s of speech, voice ${VOICE}`);
