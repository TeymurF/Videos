"""Synthesizes the Russian narration with the Piper neural TTS (voice ru_RU-ruslan-medium).
  python3 narrate_ru.py [--model path/to/ru_RU-ruslan-medium.onnx]
Reads the Russian texts from ru.json (one entry per cue, key <scene>_<n>), writes
out/narration/<scene>_<n>.wav and src/narration.js (clip durations used to time the captions).
Captions on screen stay in English. Model: https://huggingface.co/rhasspy/piper-voices (ru/ru_RU)."""
import json, os, re, sys, wave
import numpy as np
from piper import PiperVoice

arg = lambda k, d: sys.argv[sys.argv.index('--' + k) + 1] if '--' + k in sys.argv else d
MODEL = arg('model', 'models/ru_RU-ruslan-medium.onnx')
DIR = 'out/narration'
os.makedirs(DIR, exist_ok=True)
voice = PiperVoice.load(MODEL)
SR = voice.config.sample_rate
ru = json.load(open('ru.json', encoding='utf-8'))
meta = json.load(open('out/meta.json'))

def trim(a, th=0.004):
    idx = np.where(np.abs(a) > th)[0]
    if not len(idx): return a
    return a[max(0, idx[0] - int(SR * .025)):min(len(a), idx[-1] + int(SR * .05))]

def speak(text):
    parts = []
    for sent in [x.strip() for x in re.findall(r'[^.!?]+[.!?]+|[^.!?]+$', text) if x.strip()]:
        chunks = [c.audio_float_array for c in voice.synthesize(sent)]
        parts.append(trim(np.concatenate(chunks)))
        parts.append(np.zeros(int(SR * .28)))
    return np.concatenate(parts[:-1])

durs, total = {}, 0
for s in meta['scenes']:
    durs[s['id']] = []
    for i in range(len(s['cues'])):
        key = f"{s['id']}_{i}"
        a = speak(ru[key])
        pcm = (np.clip(a, -1, 1) * 32767).astype('<i2')
        with wave.open(f'{DIR}/{key}.wav', 'wb') as w:
            w.setnchannels(1); w.setsampwidth(2); w.setframerate(SR); w.writeframes(pcm.tobytes())
        d = len(a) / SR; durs[s['id']].append(round(d, 3)); total += d
        print(key, f'{d:.2f} s', flush=True)
open('src/narration.js', 'w').write(f"// Generated by narrate_ru.py: Russian narration clip durations in seconds (Piper ru_RU-ruslan-medium).\nwindow.NARR = {json.dumps(durs)};\n")
print(f'narration: {total:.1f} s of speech')
